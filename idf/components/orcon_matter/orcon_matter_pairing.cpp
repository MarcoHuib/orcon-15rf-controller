using WindowStatus = chip::app::Clusters::AdministratorCommissioning::CommissioningWindowStatusEnum;
constexpr uint32_t kWindowS = 900;   // the spec's maximum for a commissioned device (15 minutes)
WebServer* g_srv = nullptr;
uint32_t g_openedMs = 0;
bool g_ourWindow = false;   // this page opened the open window (so its remaining time is known)
// The owner's activation: 0 idle, 1 making the identity (its own task), 2 failed, 3 made (the loop task restarts)
std::atomic<int> g_activation{0};

// What the page shows. A window with this controller's own code: opened locally (here) or by an administrator as a
// basic window (OBCW). An enhanced window (OCW, "share with another app") carries THAT controller's code, not ours.
enum class Win : uint8_t { Closed, OwnCode, OtherCode };
struct Status { bool ready = false; Win win = Win::Closed; bool failsafe = false; unsigned fabrics = 0; uint32_t leftS = 0; };

Status statusLocked() {
    Status s;
    s.ready = orcon_matter::matterReady();
    if (!s.ready) return s;
    chip::Server& srv = chip::Server::GetInstance();
    auto& cwm = srv.GetCommissioningWindowManager();
    if (cwm.IsCommissioningWindowOpen())
        s.win = cwm.CommissioningWindowStatusForCluster() == WindowStatus::kEnhancedWindowOpen ? Win::OtherCode : Win::OwnCode;
    s.failsafe = srv.GetFailSafeContext().IsFailSafeArmed();
    s.fabrics = srv.GetFabricTable().FabricCount();
    const uint32_t gone = (millis() - g_openedMs) / 1000;
    s.leftS = s.win == Win::OwnCode && g_ourWindow && gone < kWindowS ? kWindowS - gone : 0;
    return s;
}

using orcon_matter::MatterHistory;
using Kind = MatterHistory::Kind;
MatterHistory g_history;

class FabricHistory final : public chip::FabricTable::Delegate {
    uint16_t leavingVendor_ = 0;   // Delete calls both callbacks synchronously under the stack lock.
    void record(Kind kind, const chip::FabricTable& table, chip::FabricIndex index) {
        const auto* fabric = table.FindFabricWithIndex(index);
        if (fabric) g_history.add(kind, millis(), index, static_cast<uint16_t>(fabric->GetVendorId()));
    }
public:
    void OnFabricUpdated(const chip::FabricTable& table, chip::FabricIndex index) override {
        // UpdateNOC also uses this hook. AddNOC is identifiable by a new index in the table.
        ++g_history.revision;
        if (known_[index / 8] & (1u << (index % 8))) return;
        known_[index / 8] |= 1u << (index % 8);
        g_history.setAdded(index, true);
        record(Kind::FabricPending, table, index);
    }
    void OnFabricCommitted(const chip::FabricTable& table, chip::FabricIndex index) override {
        record(Kind::FabricCommitted, table, index);
    }
    void FabricWillBeRemoved(const chip::FabricTable& table, chip::FabricIndex index) override {
        const auto* fabric = table.FindFabricWithIndex(index);
        leavingVendor_ = fabric ? static_cast<uint16_t>(fabric->GetVendorId()) : 0;
    }
    void OnFabricRemoved(const chip::FabricTable&, chip::FabricIndex index) override {
        ++g_history.revision;
        known_[index / 8] &= ~(1u << (index % 8));
        g_history.setAdded(index, false);
        g_history.add(Kind::FabricRemoved, millis(), index, leavingVendor_);
    }
    void seed(const chip::FabricTable& table) {
        for (const auto& fabric : table) {
            const unsigned index = fabric.GetFabricIndex();
            known_[index / 8] |= 1u << (index % 8);
        }
    }
private:
    uint8_t known_[32]{};
} g_fabricHistory;

// JSON into the shared response buffer (orcon_matter_out.h): a full buffer turns the answer into an error, never
// into broken JSON.
using orcon_matter::Out;

void send(int code, Out& o) {
    g_srv->sendHeader("Cache-Control", "no-store");
    if (o.full) { g_srv->send(500, "application/json", "{\"error\":\"answer-too-long\"}"); return; }
    g_srv->send(code, "application/json", o.b);
}

void reply(int code, const char* err, bool summary = false) {
    const bool ready = orcon_matter::matterReady();
    if (ready) chip::DeviceLayer::PlatformMgr().LockChipStack();
    const Status s = ready ? statusLocked() : Status{};
    size_t cap = 0;
    Out o{setupweb::responseBuffer(cap), cap};
    o.fmt("{\"state\":\"%s\",\"identity\":\"%s\",\"activating\":%s,\"fabrics\":%u,\"window\":%s,\"window_code\":%s,"
          "\"window_s\":%lu,\"error\":\"%s\"", orcon_matter::matterStateName(), orcon_matter::identity::stateName(),
          g_activation.load() == 1 || g_activation.load() == 3 ? "true" : "false", s.fabrics, s.win != Win::Closed ? "true" : "false",
          s.win == Win::OwnCode ? "true" : "false", (unsigned long)s.leftS, err);
    if (!summary) {
        if (s.win == Win::OwnCode) {   // the codes only while they open this controller (never for a closed window)
            o.fmt(",\"code\":");
            o.str(orcon_matter::manualCode(), strlen(orcon_matter::manualCode()));
            o.fmt(",\"qr\":");
            o.str(orcon_matter::qrCode(), strlen(orcon_matter::qrCode()));
        }
        o.fmt(",\"commissioning\":%s,\"fabric_revision\":%lu,\"controllers\":[",
              s.failsafe || (ready && g_history.pase) ? "true" : "false",
              ready ? static_cast<unsigned long>(g_history.revision) : 0ul);
        if (s.ready) {
            bool first = true;
            for (const auto& fi : chip::Server::GetInstance().GetFabricTable()) {
                const chip::CharSpan label = fi.GetFabricLabel();
                o.fmt("%s{\"index\":%u,\"vendor\":%u,\"label\":", first ? "" : ",", unsigned(fi.GetFabricIndex()),
                      static_cast<unsigned>(fi.GetVendorId()));
                o.str(label.data(), label.size());
                o.fmt(",\"added\":%s}", g_history.added(fi.GetFabricIndex()) ? "true" : "false");
                first = false;
            }
        }
        o.fmt("]");
    }
    if (ready) chip::DeviceLayer::PlatformMgr().UnlockChipStack();
    if (!summary) {
        o.fmt(",\"diag\":");
        orcon_matter::stateJson(o);
        o.fmt(",\"control\":");
        orcon_matter::controlJson(o);
        o.fmt(",\"fan\":");
        orcon_matter::fanCheckJson(o);
    }
    o.fmt("}");
    send(code, o);
}

void handlePublicState() {   // no login: no secrets, only why Matter is (not) ready (a trial boot's confirmation)
    char b[200];
    Out o{b, sizeof b};
    orcon_matter::stateJson(o);
    send(200, o);
}

void handleStatus() {
    if (!setupweb::authorize(false, false)) return;
    reply(200, "", g_srv->arg("view") == "summary");
}

// A mutation's JSON body: small, an object, parsed whole (authorize() already checked the session, the CSRF token,
// the own origin and the JSON content type).
bool body(JsonDocument& doc) {
    const String& p = g_srv->arg("plain");
    return p.length() <= 64 && !deserializeJson(doc, p) && doc.is<JsonObject>();
}

void handleWindow() {
    if (!setupweb::authorize(true, false)) return;
    JsonDocument doc;
    if (!body(doc)) { reply(400, "bad-request"); return; }
    if (!doc["open"].isNull() && !doc["open"].is<bool>()) { reply(400, "bad-request"); return; }
    const bool open = doc["open"] | true;   // {} (an older page) opens too
    if (!orcon_matter::matterReady()) { reply(409, "matter-not-ready"); return; }
    chip::DeviceLayer::PlatformMgr().LockChipStack();
    auto& cwm = chip::Server::GetInstance().GetCommissioningWindowManager();
    const auto& failSafe = chip::Server::GetInstance().GetFailSafeContext();
    if (open && (failSafe.IsFailSafeArmed() || g_history.pase)) {
        chip::DeviceLayer::PlatformMgr().UnlockChipStack();
        reply(409, "commissioning-busy");
        return;
    }
    CHIP_ERROR e = CHIP_NO_ERROR;
    if (open && !cwm.IsCommissioningWindowOpen()) {
        e = cwm.OpenBasicCommissioningWindow(chip::System::Clock::Seconds32(kWindowS),
                                             chip::CommissioningWindowAdvertisement::kDnssdOnly);
        if (e == CHIP_NO_ERROR) { g_openedMs = millis(); g_ourWindow = true; }
    } else if (!open && cwm.IsCommissioningWindowOpen()) {
        cwm.CloseCommissioningWindow();
        g_ourWindow = false;
    }
    chip::DeviceLayer::PlatformMgr().UnlockChipStack();
    reply(e == CHIP_NO_ERROR ? 200 : 500, e == CHIP_NO_ERROR ? "" : "window-failed");
}

void handleRemove() {
    if (!setupweb::authorize(true, false)) return;
    JsonDocument doc;
    if (!body(doc) || !doc["index"].is<unsigned>() || !doc["revision"].is<uint32_t>() ||
        !doc["confirm"].is<bool>() || !doc["confirm"].as<bool>()) {
        reply(400, "bad-request");
        return;
    }
    const unsigned index = doc["index"];
    if (!orcon_matter::matterReady()) { reply(409, "matter-not-ready"); return; }
    if (index < 1 || index > 254) { reply(404, "no-such-controller"); return; }
    if (ota::writerBusy() || net::restartQueued()) { reply(409, "restart-pending"); return; }
    chip::DeviceLayer::PlatformMgr().LockChipStack();
    chip::Server& srv = chip::Server::GetInstance();
    auto& table = srv.GetFabricTable();
    const auto fabric = chip::FabricIndex(index);
    const char* err = "";
    int code = 200;
    if (srv.GetFailSafeContext().IsFailSafeArmed() || g_history.pase ||
        srv.GetCommissioningWindowManager().IsCommissioningWindowOpen()) {
        err = "commissioning-busy";
        code = 409;
    } else if (!table.FindFabricWithIndex(fabric)) {
        err = "no-such-controller";
        code = 404;
    } else if (!g_history.tracking || doc["revision"].as<uint32_t>() != g_history.revision) {
        err = "fabric-list-changed";
        code = 409;
    } else {
        // Native RemoveFabric uses Delete, which calls the SDK's server and OpCreds delegates.
        // This HTTP request has no Matter exchange that needs to remain open for the response.
        const CHIP_ERROR removed = table.Delete(fabric);
        const bool absent = !table.FindFabricWithIndex(fabric);
        if (absent) srv.GetSecureSessionManager().ExpireAllSessionsForFabric(fabric);
        if (removed != CHIP_NO_ERROR || !absent) {
            g_history.add(Kind::LocalRemoveError, millis(), fabric, 0, removed.AsInteger());
            err = "remove-failed";
            code = 500;
        }
    }
    chip::DeviceLayer::PlatformMgr().UnlockChipStack();
    reply(code, err);
}

void handleDiagnostics() {
    if (!setupweb::authorize(false, false)) return;
    size_t cap = 0;
    Out o{setupweb::responseBuffer(cap), cap};
    const auto* app = esp_app_get_description();
    o.fmt("{\"schema\":1,\"build\":");
    o.str(app->version, strnlen(app->version, sizeof app->version));
    auto* sta = esp_netif_get_handle_from_ifkey("WIFI_STA_DEF");
    esp_ip6_addr_t linkLocal{};
    constexpr uint32_t caps = MALLOC_CAP_INTERNAL | MALLOC_CAP_8BIT;
    o.fmt(",\"reset\":%u,\"wifi_up\":%u,\"ipv6_link_local\":%u,"
          "\"heap\":[%u,%u,%u],\"state\":", unsigned(esp_reset_reason()),
          unsigned(sta && esp_netif_is_netif_up(sta)),
          unsigned(sta && esp_netif_get_ip6_linklocal(sta, &linkLocal) == ESP_OK),
          unsigned(heap_caps_get_free_size(caps)), unsigned(heap_caps_get_minimum_free_size(caps)),
          unsigned(heap_caps_get_largest_free_block(caps)));
    orcon_matter::stateJson(o);
    o.fmt(",\"control\":");
    orcon_matter::controlJson(o);
    o.fmt(",\"fan_boot\":");
    orcon_matter::fanCheckJson(o);
    o.fmt(",\"snapshot\":");
    if (!orcon_matter::matterReady()) {
        o.fmt("null");
    } else {
        chip::DeviceLayer::PlatformMgr().LockChipStack();
        const Status s = statusLocked();
        o.fmt("{\"fabrics\":[");
        bool first = true;
        for (const auto& f : chip::Server::GetInstance().GetFabricTable()) {
            const unsigned idx = f.GetFabricIndex();
            o.fmt("%s[%u,%u,%u]", first ? "" : ",", idx, static_cast<unsigned>(f.GetVendorId()),
                  unsigned(g_history.added(idx)));
            first = false;
        }
        o.fmt("],\"count\":%u,\"window\":%u,\"fail_safe\":%u,\"pase\":%u,\"attempts\":%lu,"
              "\"tracking\":%u,\"dropped\":%lu,\"events\":[", s.fabrics, unsigned(s.win), unsigned(s.failsafe),
              unsigned(g_history.pase), static_cast<unsigned long>(g_history.attempts),
              unsigned(g_history.tracking), static_cast<unsigned long>(g_history.dropped));
        constexpr const char* names[] = {
            "ready", "window-open", "window-closed", "pase-start", "pase-stop", "complete", "fail-safe-expired",
            "fabric-pending", "fabric-commit", "fabric-remove", "local-remove-error", "dnssd-ready",
        };
        for (unsigned i = 0; i < g_history.size(); ++i) {
            const auto& e = g_history.at(i);
            o.fmt("%s[%lu,\"%s\",%u,%u,%lu]", i ? "," : "", static_cast<unsigned long>(e.ms), names[unsigned(e.kind)],
                  unsigned(e.index), unsigned(e.vendor), static_cast<unsigned long>(e.error));
        }
        o.fmt("],\"fan\":");
        orcon_matter::liveFanJson(o);
        o.fmt("}");
        chip::DeviceLayer::PlatformMgr().UnlockChipStack();
    }
    o.fmt("}");
    send(200, o);
}

// The identity is made in its own task (keys, certificates, the SPAKE2+ verifier: seconds, and more stack than a web
// handler has); Matter is off while there is none, so nothing else uses its NVS meanwhile.
void activationTask(void* replace) {
    namespace id = orcon_matter::identity;
    esp_err_t err = replace ? id::erase() : ESP_OK;
    if (err == ESP_OK) err = id::generate();
    g_activation = err == ESP_OK ? 3 : 2;
    vTaskDelete(nullptr);
}

bool trialBoot() {
    esp_ota_img_states_t st;
    return esp_ota_get_state_partition(esp_ota_get_running_partition(), &st) == ESP_OK && st == ESP_OTA_IMG_PENDING_VERIFY;
}

void handleActivate() {
    if (!setupweb::authorize(true, false)) return;
    namespace id = orcon_matter::identity;
    JsonDocument doc;
    if (!body(doc) || !doc["action"].is<const char*>()) { reply(400, "bad-request"); return; }
    const bool replace = !strcmp(doc["action"], "replace");
    if (!replace && strcmp(doc["action"], "activate")) { reply(400, "bad-request"); return; }
    if (replace && !(doc["confirm"] | false)) { reply(400, "bad-request"); return; }   // explicit: a new device
    const int busy = g_activation.load();
    if (busy == 1 || busy == 3) { reply(409, "activation-busy"); return; }
    if (id::state() == id::State::Valid) { reply(409, "already-activated"); return; }
    if (id::state() == id::State::Unknown) { reply(409, "matter-storage-unavailable"); return; }
    if (replace != (id::state() == id::State::Damaged)) { reply(409, replace ? "identity-not-damaged" : "identity-damaged"); return; }
    if (trialBoot()) { reply(409, "trial-boot"); return; }   // the restart would undo the update being tried
    if (net::restartQueued() || ota::writerBusy()) { reply(409, "restart-pending"); return; }
    g_activation = 1;
    if (xTaskCreatePinnedToCore(activationTask, "mtr_id", 10240, replace ? &g_activation : nullptr, 1, nullptr, 1) != pdPASS) {
        g_activation = 2;
        reply(500, "activation-failed");
        return;
    }
    reply(202, "");
}

void handlePage() {   // static: the status and the codes come from /api/connect, behind the login
    g_srv->sendHeader("Cache-Control", "no-store");
    if (g_srv->header("Accept-Encoding").indexOf("gzip") < 0) {   // stored gzip-only, as Orcon's own page
        g_srv->send(406, "text/plain", "gzip required");
        return;
    }
    g_srv->sendHeader("Content-Encoding", "gzip");
    g_srv->send_P(200, "text/html; charset=utf-8", (PGM_P)CONNECT_PAGE_GZ, CONNECT_PAGE_GZ_LEN);
}
