// The owner's page for the smart-home connection (Matter) and its API. The address names no protocol (/connect).
//   GET  /connect                     the page: gzip from flash (orcon_connect_page.html), static, no data in it
//   GET  /api/connect                 owner: status, controllers, diagnostics; the pairing codes ONLY while a window
//                                     with this controller's own code is open
//   GET  /api/connect?view=summary    owner: state, number of controllers, window (the dashboard card): no codes
//   GET  /api/connect/state           public, no login, no secrets: why Matter is (not) ready (trial-boot check)
//   POST /api/connect/window          owner + CSRF: {"open":true} opens for 15 minutes, {"open":false} closes
//   POST /api/connect/remove          owner + CSRF: {"index":N,"confirm":true} removes one controller (fabric)
//   POST /api/connect/activate        owner + CSRF: {"action":"activate"} makes this device's Matter identity on the
//                                     device (orcon_matter_identity.h) and restarts into Matter; {"action":"replace",
//                                     "confirm":true} only after damage (a new device for every controller)
// Pairing only on the owner's request (CONFIG_CHIP_ENABLE_PAIRING_AUTOSTART=n). Every route sits behind Orcon's own
// web login (setupweb::authorize): a GET needs the session, a change also its CSRF token, JSON and the own origin.
// Codes never in a public route, a log line or a cache: Cache-Control no-store on every answer, the page itself holds
// none, and nothing here prints them. Matter only runs on the home network, never next to Orcon's setup AP.
// orcon_fwup_defer(): Orcon's update job waits while a controller commissions this device (fw_update_esp.cpp).
