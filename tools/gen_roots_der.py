#!/usr/bin/env python3
"""Writes src/fw_update_roots_der.h: the nine pinned roots of src/fw_update_roots.h as DER arrays (flash), for the
Matter build's trusted-CA callback (src/fw_update_roots_cb.h). Same certificates, nothing added or dropped:
- every PEM block of FWUP_ROOTS_PEM is decoded in order;
- the SHA-256 of each DER must equal the fingerprint pinned in the comment above it (the reviewed list);
- tools/test_tx_poc_safety.py regenerates it and requires the committed file to match byte for byte.

usage: python3 -I tools/gen_roots_der.py src/fw_update_roots.h src/fw_update_roots_der.h
"""
import base64, hashlib, re, sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
body = re.search(r"FWUP_ROOTS_PEM\[\] =(.*?);", text, re.S).group(1)
fps = re.findall(r"//\s*sha256 ([0-9a-f]{64})", body)
names = re.findall(r"CN = ([^\n]*)\n\s*// sha256", body)
blocks = re.findall(r'"-----BEGIN CERTIFICATE-----\\n"(.*?)"-----END CERTIFICATE-----\\n"', body, re.S)
assert len(blocks) == len(fps) == len(names) == 9, (len(blocks), len(fps), len(names))

total = 0
out = ["// Generated by gen_roots_der.py from fw_update_roots.h: the same nine roots as DER (flash). Do not edit.",
       "#pragma once", "#include <stddef.h>", "#include <stdint.h>", ""]
for i, (b, fp) in enumerate(zip(blocks, fps)):
    der = base64.b64decode("".join(re.findall(r'"([A-Za-z0-9+/=]+)\\n"', b)), validate=True)
    assert hashlib.sha256(der).hexdigest() == fp, f"root {i}: DER does not match its pinned fingerprint"
    total += len(der)
    rows = [", ".join(f"0x{x:02x}" for x in der[k:k + 16]) for k in range(0, len(der), 16)]
    out += [f"static const uint8_t ROOT_DER_{i}[{len(der)}] = {{", *("    " + r + "," for r in rows), "};"]
n = len(blocks)
out += ["", f"static const int ROOT_N = {n};",
        "static const uint8_t* const ROOT_DER[] = {" + ", ".join(f"ROOT_DER_{i}" for i in range(n)) + "};",
        "static const size_t ROOT_DER_LEN[] = {" + ", ".join(f"sizeof(ROOT_DER_{i})" for i in range(n)) + "};",
        "static const char* const ROOT_SHA256[] = {" + ", ".join(f'"{f}"' for f in fps) + "};",
        "static const char* const ROOT_NAME[] = {" + ", ".join('"' + m.strip() + '"' for m in names) + "};", ""]
open(dst, "w", encoding="ascii").write("\n".join(out))
print(f"{n} roots, {total} bytes DER, fingerprints ok")
