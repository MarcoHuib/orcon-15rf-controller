#!/usr/bin/env bash
# A device's own Matter identity, made once, instead of the SDK's public test set (a test DAC with a published key,
# passcode 20202021, discriminator 3840):
#   tools/matter_identity.sh            -> ~/.orcon-matter (or $OUT), mode 0700
# Offline, in the pinned ESP-Matter container: an own PAA -> PAI -> DAC chain (vendor ID 0xFFF1 / product ID 0x8000: the
# TEST vendor range; this project has no vendor ID of its own and is not certified, so Apple Home warns "niet-
# gecertificeerd accessoire" and asks before adding it), an own signed certification declaration, a random passcode and
# discriminator with their SPAKE2+ verifier, the pairing codes, and a random serial number.
# Everything stays in that directory, OUTSIDE the repository: orcon_matter_creds.h (for tools/build_idf.sh --identity),
# identity.defaults (the serial number), KOPPELCODE.txt and the keys. An existing identity is reused, never replaced: a
# new one is a new device for every controller it was paired with. The header and every image built with it hold this
# device's DAC private key and setup code: never publish or commit them (docs/MATTER.md, "Eigen Matter-identiteit").
set -euo pipefail
image=espressif/esp-matter@sha256:94ed6a211d5bc6b55c44a36802bdb0e663a92d9aac7ece3944e6a1bec10a7f17
out=${OUT:-$HOME/.orcon-matter}
case $out in "$(cd "$(dirname "$0")/.." && pwd)"*) echo "refusing: $out lies inside the repository" >&2; exit 2;; esac
umask 077; mkdir -p "$out"; chmod 700 "$out"
if [ ! -s "$out/orcon_matter_creds.h" ]; then
    [ ! -e "$out/dac-key.pem" ] || { echo "$out has keys but no header: refusing to make a second identity" >&2; exit 1; }
    docker run --rm --network none -u "$(id -u):$(id -g)" -v "$out:/out" "$image" bash -c '
set -euo pipefail; cd /out; umask 077
C=/opt/espressif/esp-matter/connectedhomeip/connectedhomeip
L=4294967295   # no well-defined expiration (99991231235959Z)
chip-cert gen-att-cert -t a -c "Orcon 15RF zelfbouw PAA" -V FFF1 -l $L -o paa-cert.pem -O paa-key.pem
chip-cert gen-att-cert -t i -c "Orcon 15RF zelfbouw PAI" -V FFF1 -P 8000 -C paa-cert.pem -K paa-key.pem -l $L -o pai-cert.pem -O pai-key.pem
chip-cert gen-att-cert -t d -c "Orcon 15RF controller" -V FFF1 -P 8000 -C pai-cert.pem -K pai-key.pem -l $L -o dac-cert.pem -O dac-key.pem
chip-cert validate-att-cert -d dac-cert.pem -i pai-cert.pem -a paa-cert.pem
chip-cert gen-att-cert -t a -c "Orcon 15RF zelfbouw CD" -V FFF1 -l $L -o cd-signer-cert.pem -O cd-signer-key.pem
chip-cert gen-cd -K cd-signer-key.pem -C cd-signer-cert.pem -O cd.der -f 1 -V FFF1 -p 8000 -d 002B \
    -c ZELFBOUW-0000001-26 -l 0 -i 0 -n 0001 -t 0
/opt/espressif/tools/python_env/idf5.5_py3.12_env/bin/python3 -I - "$C" <<"EOF"
import os, secrets, sys
sys.path[:0] = [sys.argv[1] + "/scripts/tools/spake2p", sys.argv[1] + "/src/setup_payload/python"]
from spake2p import INVALID_PASSCODES, generate_verifier
from SetupPayload import SetupPayload
from cryptography import x509
from cryptography.hazmat.primitives import serialization as ser
while True:
    pin = secrets.randbelow(99999998) + 1
    if pin not in INVALID_PASSCODES: break
disc = secrets.randbelow(4096)
while disc == 3840: disc = secrets.randbelow(4096)      # never the SDK test discriminator
salt, it = os.urandom(32), 10000
ver = generate_verifier(pin, salt, it)
pay = SetupPayload(disc, pin, rendezvous=4, vid=0xFFF1, pid=0x8000)    # 4: on-network discovery (no BLE in this build)
qr, manual = pay.generate_qrcode(), pay.generate_manualcode()
der = lambda f: x509.load_pem_x509_certificate(open(f, "rb").read()).public_bytes(ser.Encoding.DER)
key = ser.load_pem_private_key(open("dac-key.pem", "rb").read(), None)
priv = key.private_numbers().private_value.to_bytes(32, "big")
pub = key.public_key().public_bytes(ser.Encoding.X962, ser.PublicFormat.UncompressedPoint)
arr = lambda n, b: "static const uint8_t %s[%d] = {%s};" % (n, len(b), ", ".join("0x%02x" % x for x in b))
h = ["// Generated by tools/matter_identity.sh: the Matter identity of ONE device. SECRET: the DAC private key and the",
     "// setup code. Never publish or commit this file or an image built with it.",
     "#pragma once", "#include <stdint.h>", "namespace orcon_matter_creds {",
     "constexpr uint16_t kVendorId = 0xFFF1, kProductId = 0x8000, kDiscriminator = %d;" % disc,
     "constexpr uint32_t kPasscode = %d, kIterations = %d;" % (pin, it),
     arr("kSalt", salt), arr("kVerifier", ver), arr("kDacCert", der("dac-cert.pem")), arr("kPaiCert", der("pai-cert.pem")),
     arr("kCd", open("cd.der", "rb").read()), arr("kDacPublic", pub), arr("kDacPrivate", priv),
     "static const char kManualCode[] = \"%s\";" % manual, "static const char kQrCode[] = \"%s\";" % qr, "}", ""]
open("orcon_matter_creds.h", "w").write("\n".join(h))
open("KOPPELCODE.txt", "w").write("Matter-koppelcode (handmatig): %s\nQR-inhoud: %s\nDiscriminator: %d\n" % (manual, qr, disc))
EOF
' 2>&1 | grep -v -E "^$"
fi
grep -q "kDacPrivate\[32\]" "$out/orcon_matter_creds.h" && grep -q "kVerifier\[97\]" "$out/orcon_matter_creds.h"
if [ ! -s "$out/identity.defaults" ]; then   # the device's serial number (Basic Information), random, kept with its identity
    printf 'CONFIG_USE_TEST_SERIAL_NUMBER="ORC-%s"\n' "$(od -An -N3 -tx1 /dev/urandom | tr -d ' \n' | tr a-f A-F)" > "$out/identity.defaults"
fi
echo "identity: $out (0700). Build: tools/build_idf.sh --identity $out. Pairing code: $out/KOPPELCODE.txt"
