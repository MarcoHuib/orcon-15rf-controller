"""gen_connect_page.py [--check]: idf/components/orcon_matter/ orcon_connect_page.html -> orcon_connect_page.h, gzip -9 (mtime 0) as a
PROGMEM byte array, served with Content-Encoding: gzip by orcon_matter_pairing.cpp (as tools/gen_setup_page.py does for
Orcon's own page). --check: exit 1 unless the header decompresses to exactly the current HTML."""
import gzip
import pathlib
import re
import sys

comp = pathlib.Path(__file__).resolve().parent.parent / "idf/components/orcon_matter"
SRC, OUT = comp / "orcon_connect_page.html", comp / "orcon_connect_page.h"
html = SRC.read_bytes()

if "--check" in sys.argv:
    body = OUT.read_text()
    data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", body.split("{", 1)[1].split("}", 1)[0]))
    n = int(re.search(r"CONNECT_PAGE_GZ_LEN = (\d+)", body).group(1))
    ok = len(data) == n and gzip.decompress(data) == html
    print("orcon_connect_page.h " + ("matches orcon_connect_page.html" if ok else "is STALE: run tools/gen_connect_page.py"))
    sys.exit(0 if ok else 1)

gz = gzip.compress(html, 9, mtime=0)
rows = ",\n".join(",".join(f"0x{b:02x}" for b in gz[i:i + 24]) for i in range(0, len(gz), 24))
OUT.write_text(
    "// Generated by tools/gen_connect_page.py from orcon_connect_page.html. Do not edit.\n"
    f"// {len(html)} B HTML -> {len(gz)} B gzip (Content-Encoding: gzip).\n"
    "#pragma once\n#include <stdint.h>\n#include <stddef.h>\n"
    "#ifndef PROGMEM\n#define PROGMEM\n#endif\n"
    f"static const uint8_t CONNECT_PAGE_GZ[] PROGMEM = {{\n{rows}\n}};\n"
    f"static const size_t CONNECT_PAGE_GZ_LEN = {len(gz)};\n")
print(f"{len(html)} B HTML -> {len(gz)} B gzip")
