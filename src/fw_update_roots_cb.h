// The nine pinned roots of fw_update_roots.h on demand (Matter builds; QEMU-tested in the research environment): mbedTLS's
// trusted-CA callback instead of parsing all nine before every handshake (-17.3 KB at the TLS peak). For each
// certificate whose parent mbedTLS looks for, it offers exactly the pinned roots whose subject equals that certificate's
// issuer by mbedTLS's own comparison; mbedTLS then runs its unchanged chain and host name checks (VERIFY_REQUIRED).
// A failing callback fails the handshake: never an unverified connection. Needs CONFIG_MBEDTLS_X509_TRUSTED_CERT_CALLBACK.
// fw_update_roots_der.h is generated by tools/gen_roots_der.py from fw_update_roots.h (same roots, fingerprints checked).
#pragma once
#include <NetworkClientSecure.h>
#include <mbedtls/platform.h>
#include <mbedtls/ssl.h>
#include <mbedtls/x509_crt.h>
#include <string.h>
#include "fw_update_roots_der.h"

namespace rootscb {
// Copies of mbedTLS 3.6.6 library/x509_crt.c x509_memcasecmp / x509_string_cmp / x509_name_cmp (static there).
static int memcasecmp(const void* s1, const void* s2, size_t len) {
    const unsigned char *n1 = (const unsigned char*)s1, *n2 = (const unsigned char*)s2;
    for (size_t i = 0; i < len; i++) {
        const unsigned char diff = n1[i] ^ n2[i];
        if (diff == 0) continue;
        if (diff == 32 && ((n1[i] >= 'a' && n1[i] <= 'z') || (n1[i] >= 'A' && n1[i] <= 'Z'))) continue;
        return -1;
    }
    return 0;
}
static int stringCmp(const mbedtls_x509_buf* a, const mbedtls_x509_buf* b) {
    if (a->tag == b->tag && a->len == b->len && memcmp(a->p, b->p, b->len) == 0) return 0;
    if ((a->tag == MBEDTLS_ASN1_UTF8_STRING || a->tag == MBEDTLS_ASN1_PRINTABLE_STRING) &&
        (b->tag == MBEDTLS_ASN1_UTF8_STRING || b->tag == MBEDTLS_ASN1_PRINTABLE_STRING) &&
        a->len == b->len && memcasecmp(a->p, b->p, b->len) == 0) return 0;
    return -1;
}
static int nameCmp(const mbedtls_x509_name* a, const mbedtls_x509_name* b) {
    while (a != NULL || b != NULL) {
        if (a == NULL || b == NULL) return -1;
        if (a->oid.tag != b->oid.tag || a->oid.len != b->oid.len || memcmp(a->oid.p, b->oid.p, b->oid.len) != 0) return -1;
        if (stringCmp(&a->val, &b->val) != 0) return -1;
        if (a->MBEDTLS_PRIVATE(next_merged) != b->MBEDTLS_PRIVATE(next_merged)) return -1;
        a = a->next;
        b = b->next;
    }
    return 0;
}
static int caCallback(void*, mbedtls_x509_crt const* child, mbedtls_x509_crt** candidates) {
    *candidates = nullptr;
    mbedtls_x509_crt* list = nullptr;
    for (int i = 0; i < ROOT_N; ++i) {
        mbedtls_x509_crt root;
        mbedtls_x509_crt_init(&root);
        if (mbedtls_x509_crt_parse_der_nocopy(&root, ROOT_DER[i], ROOT_DER_LEN[i]) != 0) { mbedtls_x509_crt_free(&root); goto fail; }
        const bool match = nameCmp(&child->issuer, &root.subject) == 0;
        mbedtls_x509_crt_free(&root);
        if (!match) continue;
        if (!list) {
            list = (mbedtls_x509_crt*)mbedtls_calloc(1, sizeof(*list));
            if (!list) goto fail;
            mbedtls_x509_crt_init(list);
        }
        if (mbedtls_x509_crt_parse_der_nocopy(list, ROOT_DER[i], ROOT_DER_LEN[i]) != 0) goto fail;
    }
    *candidates = list;   // mbedTLS frees it after this parent search
    return 0;
fail:
    if (list) { mbedtls_x509_crt_free(list); mbedtls_free(list); }
    return -1;            // MBEDTLS_ERR_X509_FATAL_ERROR: the handshake fails, never an unverified connection
}
static esp_err_t attach(void* conf) {
    mbedtls_ssl_conf_authmode((mbedtls_ssl_config*)conf, MBEDTLS_SSL_VERIFY_REQUIRED);
    mbedtls_ssl_conf_ca_cb((mbedtls_ssl_config*)conf, caCallback, nullptr);
    return ESP_OK;
}
struct Client : NetworkClientSecure {   // the protected members Arduino's own CA-bundle setter uses
    Client() { sslclient->bundle_attach_cb = attach; _use_ca_bundle = true; }
};
}  // namespace rootscb
